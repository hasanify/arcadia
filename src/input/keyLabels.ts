export function getFriendlyKeyLabel(code: string): string {
  if (FRIENDLY_KEY_LABELS[code]) {
    return FRIENDLY_KEY_LABELS[code];
  }
  return code.replace(/^Key/, '').replace(/^Digit/, '');
}
